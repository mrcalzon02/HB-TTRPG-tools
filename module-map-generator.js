(function (root, factory) {
  const engine = root && root.HBSemanticSpatialEngine ? root.HBSemanticSpatialEngine : (typeof require === 'function' ? require('./semantic-spatial-engine.js') : null);
  const api = factory(engine);
  if (typeof module === 'object' && module.exports) module.exports = api;
  if (root) {
    root.generator = root.generator || {};
    root.generator.module_map = api;
  }
})(typeof globalThis !== 'undefined' ? globalThis : this, function (engine) {
  'use strict';
  if (!engine) throw new Error('module-map-generator requires HBSemanticSpatialEngine.');

  function makeCells(width, height) {
    return Array.from({ length: height }, () => Array.from({ length: width }, () => ({ type: 'void', label: '' })));
  }
  function set(cells, x, y, cell) {
    if (cells[y] && cells[y][x]) cells[y][x] = { ...cells[y][x], ...cell };
  }
  function drawRoom(cells, room) {
    for (let y = room.y; y < room.y + room.height; y += 1) for (let x = room.x; x < room.x + room.width; x += 1) {
      const boundary = x === room.x || y === room.y || x === room.x + room.width - 1 || y === room.y + room.height - 1;
      set(cells, x, y, { type: boundary ? 'wall' : 'floor', meta: { roomId: room.nodeId, role: room.role, deck: room.deck } });
    }
    const cx = room.x + Math.floor(room.width / 2), cy = room.y + Math.floor(room.height / 2);
    set(cells, cx, cy, { type: 'label', label: room.label || room.role, meta: { id: room.nodeId, roomId: room.nodeId, role: room.role, deck: room.deck } });
  }
  function drawCorridor(cells, corridor) {
    corridor.points.forEach(point => set(cells, point.x, point.y, { type: 'floor', meta: { corridorId: corridor.id, edgeId: corridor.edgeId, deck: corridor.deck } }));
  }

  function layoutToMap(layout, options) {
    const deck = Math.max(0, Number(options && options.deck) || 0);
    const width = layout.bounds.width, height = layout.bounds.height, cells = makeCells(width, height);
    layout.rooms.filter(room => room.deck === deck).forEach(room => drawRoom(cells, room));
    layout.corridors.filter(corridor => corridor.deck === deck).forEach(corridor => drawCorridor(cells, corridor));
    layout.doors.filter(door => door.deck === deck).forEach(door => set(cells, door.x, door.y, { type: 'door', label: '', meta: { id: door.id, roomId: door.roomId, corridorId: door.corridorId, edgeId: door.edgeId, deck } }));
    layout.connectors.filter(connector => connector.deck === deck).forEach(connector => set(cells, connector.x, connector.y, { type: 'stairs', label: '', meta: { id: connector.id, pairId: connector.pairId, connectsDeck: connector.connectsDeck, kind: connector.kind } }));
    return {
      schemaVersion: '0.1.0', tool: 'module-map-editor', generator: 'generator.module_map', width, height, tileSize: 1, cells,
      seed: layout.seed, deck, deckCount: layout.deckCount, spatialLayout: layout,
      title: (options && options.title) || 'Procedural semantic module map',
      notes: 'Generated by generator.module_map through the shared HB semantic spatial engine.'
    };
  }

  function generate(input) {
    const spec = { ...(input || {}) };
    const layout = engine.generate({
      seed: spec.seed || 'module-map',
      decks: spec.decks || 1,
      roles: spec.roles || [
        { role: 'entry', label: 'Entry', protected: true },
        { role: 'transit', label: 'Hall', protected: false, count: 2 },
        { role: 'encounter', label: 'Encounter', protected: true, count: 2 },
        { role: 'objective', label: 'Objective', protected: true },
        { role: 'reward', label: 'Reward', protected: true }
      ],
      adjacency: spec.adjacency || [ ['entry', 'transit'], ['objective', 'reward'], ['encounter', 'objective'] ],
      layout: { gridWidth: spec.width || 72, gridHeight: spec.height || 56, ...(spec.layout || {}) },
      extraEdgeChance: spec.extraEdgeChance,
      pruneDeadEnds: spec.pruneDeadEnds,
      strict: spec.strict
    });
    return layoutToMap(layout, spec);
  }

  return Object.freeze({ generate, layoutToMap });
});
