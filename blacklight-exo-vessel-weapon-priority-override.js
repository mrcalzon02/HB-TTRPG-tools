(() => {
  'use strict';
  const base=globalThis.BlacklightExoVessel,E=globalThis.BlacklightExoVesselEngineeringDefinitions,M=globalThis.BlacklightExoVesselManufacturerDefinitions;
  if(!base?.gameplayVersion||!E?.weaponFamilies||!M?.archetypeMatrices||base.weaponPriorityOverrideVersion)return;
  const normalize=value=>{
    const rows=Array.isArray(value)?value:String(value||'').split(',');
    const output=[];
    for(const raw of rows){const key=String(raw||'').trim().toUpperCase();if(!key)continue;if(!E.weaponFamilies[key])throw new Error(`Unknown weapon-family priority override ${key}.`);if(!output.includes(key))output.push(key);}
    return output;
  };
  const merged=(priority,existing)=>[...priority,...existing.filter(key=>!priority.includes(key))];
  const preferenceName=key=>E.weaponFamilies[key].aliases?.[0]||E.weaponFamilies[key].label;
  const preferenceMatches=(name,key)=>{const value=String(name||'').toLowerCase(),family=E.weaponFamilies[key];return family.aliases?.some(alias=>value.includes(String(alias).toLowerCase()))||value.includes(String(family.label||'').toLowerCase());};
  function generate(seed,input={},source=null){
    const priority=normalize(input.weaponFamilyPriority);
    if(!priority.length)return base.generate(seed,input,source);
    const role=String(input.role||'warship').toLowerCase(),originalRole=E.defaultWeaponPriority[role],originalMatrices=Object.fromEntries(Object.entries(M.archetypeMatrices).map(([key,matrix])=>[key,[...matrix.weapons]]));
    if(!originalRole)throw new Error(`Weapon-family priority override requires a known mission role; received ${role}.`);
    try{
      E.defaultWeaponPriority[role]=merged(priority,[...originalRole]);
      const preferredNames=priority.map(preferenceName);
      for(const matrix of Object.values(M.archetypeMatrices))matrix.weapons=[...preferredNames,...matrix.weapons.filter(name=>!priority.some(key=>preferenceMatches(name,key)))];
      const result=base.generate(seed,input,source),installed=new Set((result.weapons?.installations||[]).map(item=>item.weaponFamily)),rank=Number(result.drive?.pathLevelRank)||0,fit=result.weapons?.combatFit;
      const eligible=priority.filter(key=>Number(E.weaponFamilies[key].minimumRank||0)<=rank),capacity=Math.max(0,Number(fit?.maxWeaponFamilies)||0),required=eligible.slice(0,capacity);
      const missing=required.filter(key=>!installed.has(key));
      if(missing.length)throw new Error(`Canonical weapon-family priority override failed to install ${missing.join(', ')} at Path ${rank} with ${fit?.key||'unknown'} fit.`);
      result.weaponPriorityOverride={recordType:'exoVesselWeaponPriorityOverride',schemaVersion:'1.0.0',requestedFamilies:[...priority],eligibleFamilies:eligible,requiredFamilies:required,installedFamilies:[...installed],manufacturerPreferenceAliases:[...preferredNames],scope:'SINGLE_SYNCHRONOUS_GENERATION',canonicalEngineeringPreserved:true};
      result.warnings=[...(result.warnings||[]),`Explicit weapon-family priority ${priority.join(', ')} was applied for this generation before the ordinary manufacturer and role preference tables; mass, support, magazine, cooling, hardpoint, condition, engagement, damage, and gameplay authorities were still generated by their canonical phases.`];
      return result;
    }finally{
      E.defaultWeaponPriority[role]=originalRole;
      for(const[key,weapons]of Object.entries(originalMatrices))M.archetypeMatrices[key].weapons=weapons;
    }
  }
  globalThis.BlacklightExoVessel=Object.freeze({...base,weaponPriorityOverrideVersion:1,generate});
})();
